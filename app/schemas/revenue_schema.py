"""
schemas/revenue_schema.py — Pydantic models for Advanced Revenue Analysis and Analytics Services.
Milestone 3 Modules 1 & 2.
"""

from pydantic import BaseModel, ConfigDict, Field
from typing import List, Optional


class TotalRevenueResponse(BaseModel):
    """Schema for GET /analytics/revenue."""
    total_revenue: float = Field(..., description="Gross merchandise value across all transactions")


class VendorPerformanceItem(BaseModel):
    """Schema for each item in GET /analytics/vendor-performance."""
    model_config = ConfigDict(from_attributes=True)

    vendor_id: int
    amount: float = Field(..., description="Total revenue generated by the vendor")
    vendor_name: Optional[str] = Field(None, description="Registered name of the vendor")
    units_sold: Optional[int] = Field(None, description="Total units sold across vendor products")


class CustomerMetricsResponse(BaseModel):
    """Schema for GET /analytics/customers."""
    customers: int = Field(..., description="Total count of registered customers")
    avg_spend: float = Field(..., description="Average lifetime spend per customer")


class MonthlyGrowthItem(BaseModel):
    """Schema for monthly revenue aggregation and MoM growth rate."""
    year_month: str = Field(..., description="Calendar year and month in YYYY-MM format")
    month: int = Field(..., description="Month number (1-12)")
    revenue: float = Field(..., description="Total revenue for the month")
    units: int = Field(..., description="Total units sold in the month")
    orders: int = Field(..., description="Total transaction orders in the month")
    mom_growth_pct: Optional[float] = Field(
        None,
        description="Month-over-Month revenue growth percentage. Null for baseline initial month."
    )
    note: Optional[str] = Field(None, description="Contextual note (e.g. baseline month)")


class RevenueGrowthResponse(BaseModel):
    """Schema for GET /analytics/revenue/growth."""
    total_revenue: float
    average_order_value: float
    monthly_growth: List[MonthlyGrowthItem]


class VendorBenchmarkItem(BaseModel):
    """Schema for individual vendor benchmark ranking and market share."""
    vendor_id: int
    vendor_name: str
    revenue: float
    units_sold: int
    order_count: int
    rank: int = Field(..., description="Revenue rank (1 is highest revenue vendor)")
    market_share_pct: float = Field(..., description="Percentage share of total marketplace GMV")


class VendorBenchmarkResponse(BaseModel):
    """Schema for GET /analytics/revenue/benchmarking."""
    total_gmv: float
    total_vendors: int
    benchmarking: List[VendorBenchmarkItem]


class ForecastResponse(BaseModel):
    """Schema for GET /forecast/{month}."""
    month: int = Field(..., description="Forecasted month index (1-12 or future)")
    forecast: float = Field(..., description="Predicted unit demand from trained inventory model")
    units_predicted: Optional[int] = Field(None, description="Integer rounded forecast units")
    model_name: Optional[str] = Field("RandomForest", description="Forecasting model architecture")


class SingleRecommendationResponse(BaseModel):
    """Schema for GET /recommend/{customer_id}."""
    customer: int = Field(..., description="Customer ID")
    recommended_product: str = Field(..., description="Top recommended product name")
    customer_name: Optional[str] = Field(None, description="Customer name")
    category: Optional[str] = Field(None, description="Product category")
    score: Optional[float] = Field(None, description="Collaborative similarity score")
    is_personalized: Optional[bool] = Field(True, description="True if personalized collaborative, False if cold-start")
